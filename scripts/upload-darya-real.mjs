import {chromium} from 'playwright';
import {existsSync,mkdirSync,writeFileSync,readFileSync} from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
const dir=path.resolve('data/cdn-upload-darya');mkdirSync(dir,{recursive:true});
const marker=path.join(dir,'attempt.json');const name='hamkadeh-darya-cdn-upload';
const b=await chromium.connectOverCDP('http://127.0.0.1:9222',{timeout:15000});
try{
 const ctx=b.contexts()[0];let p;
 for(const candidate of ctx.pages().filter(p=>new URL(p.url()).origin==='https://cdn.hamkadeh.com')){if(await candidate.evaluate(()=>window.name)===name){p=candidate;break;}}
 if(process.argv.includes('--upload')){
  if(existsSync(marker))throw new Error('An upload attempt already exists. Inspect its result instead of uploading twice.');
  p=await ctx.newPage();p.setDefaultTimeout(30000);await p.goto('https://cdn.hamkadeh.com/',{waitUntil:'domcontentloaded'});await p.evaluate(n=>{window.name=n;},name);
  await p.locator('#upload-button').waitFor();if(new URL(p.url()).origin!=='https://cdn.hamkadeh.com')throw new Error('CDN sign-in required');
  await p.locator('#upload-button').click();await p.locator('#upload-dialog').waitFor();
  const events=[];p.on('response',r=>{if(['POST','PUT','PATCH'].includes(r.request().method())&&new URL(r.url()).origin==='https://cdn.hamkadeh.com'){events.push({method:r.request().method(),path:new URL(r.url()).pathname,status:r.status()});}});
  const chooser=p.waitForEvent('filechooser');await p.getByRole('button',{name:'Pick files',exact:true}).click();
  const fileChooser=await chooser;
  writeFileSync(marker,JSON.stringify({state:'file-selection-started',at:new Date().toISOString(),file:'#دریا_فلورا (14).jpg'}));
  await fileChooser.setFiles(path.resolve('#دریا_فلورا (14).jpg'));
  await p.locator('#upload-dialog').screenshot({path:path.join(dir,'after-selection.png')});
  writeFileSync(path.join(dir,'network-summary.json'),JSON.stringify(events,null,2));
 }
 if(!p)throw new Error('Upload tab is unavailable; do not repeat upload without checking the CDN.');
 p.setDefaultTimeout(15000);
 if(process.argv.includes('--verify')){
  const generated=readFileSync(path.join(dir,'generated-links.txt'),'utf8').trim();const url=new URL(generated);
  if(url.origin!=='https://cdn.hamkadeh.com'||url.username||url.password)throw new Error('Unexpected generated image URL');
  const r=await ctx.request.get(generated,{maxRedirects:0,timeout:30000});
  if(!r.ok()||!r.headers()['content-type']?.startsWith('image/'))throw new Error('Uploaded image is not available');
  const uploaded=await r.body();const local=readFileSync(path.resolve('#دریا_فلورا (14).jpg'));
  const hash=value=>createHash('sha256').update(value).digest('hex');
  if(hash(uploaded)!==hash(local))throw new Error('Uploaded image does not match the authorized banner');
  const verified={generatedUrl:generated,status:r.status(),contentType:r.headers()['content-type'],bytes:uploaded.length,sha256:hash(uploaded),matchesLocalFile:true,landingCreated:false,verifiedAt:new Date().toISOString()};
  writeFileSync(path.join(dir,'verified.json'),JSON.stringify(verified,null,2));
  writeFileSync(marker,JSON.stringify({...JSON.parse(readFileSync(marker,'utf8')),state:'verified',generatedUrl:generated}));
  console.log(JSON.stringify(verified));
 }
 if(process.argv.includes('--links')){
  const info=p.locator('.dialog').filter({hasText:'Info'});if(await info.count()===1)await info.getByRole('button',{name:'Close',exact:true}).click();
  // Capture only text generated by the site's own Copy links action. Never read
  // or overwrite unrelated OS clipboard contents, and restore both methods.
  await p.evaluate(()=>{
   window.__cdnCapturedLinks='';window.__cdnClipboardWrite=navigator.clipboard.writeText;
   navigator.clipboard.writeText=async text=>{window.__cdnCapturedLinks=text;};
   window.__cdnExecCommand=document.execCommand;
   document.execCommand=function(command,...args){if(command==='copy'){window.__cdnCapturedLinks=window.getSelection()?.toString()||document.activeElement?.value||'';return true;}return window.__cdnExecCommand.call(document,command,...args);};
  });
  try{
   await p.locator('#upload-dialog a').filter({hasText:/^Copy links$/}).click();
   await p.waitForFunction(()=>!!window.__cdnCapturedLinks,{},{timeout:5000});
   const links=await p.evaluate(()=>window.__cdnCapturedLinks);
   writeFileSync(path.join(dir,'generated-links.txt'),links);console.log(JSON.stringify({generatedLinks:links}));
  }finally{await p.evaluate(()=>{navigator.clipboard.writeText=window.__cdnClipboardWrite;document.execCommand=window.__cdnExecCommand;});}
 }
 if(process.argv.includes('--details'))await p.locator('#upload-dialog a').filter({hasText:/^Show details$/}).click();
 if(process.argv.includes('--send')){
  const attempt=JSON.parse(readFileSync(marker,'utf8'));if(attempt.state!=='file-selection-started')throw new Error('Send was already attempted; inspect the existing result.');
  const dialog=p.locator('#upload-dialog');if(!(await dialog.innerText()).includes('#دریا_فلورا (14).jpg'))throw new Error('Selected file does not match the authorized banner.');
  const send=dialog.getByRole('button',{name:/^Send 1 file,/});if(await send.count()!==1)throw new Error('Expected exactly one queued banner.');
  const response=p.waitForResponse(r=>new URL(r.url()).origin==='https://cdn.hamkadeh.com'&&['POST','PUT'].includes(r.request().method()),{timeout:60000});
  writeFileSync(marker,JSON.stringify({...attempt,state:'send-started',sendAt:new Date().toISOString()}));
  await send.click();const uploaded=await response;await uploaded.finished();
  const network={status:uploaded.status(),method:uploaded.request().method(),path:new URL(uploaded.url()).pathname,contentType:uploaded.headers()['content-type']};
  writeFileSync(path.join(dir,'upload-response.json'),JSON.stringify(network,null,2));console.log(JSON.stringify({uploadResponse:network}));
 }
 const result=await p.evaluate(()=>({dialogs:[...document.querySelectorAll('#upload-dialog,[role=dialog],.dialog')].map(e=>({id:e.id,text:e.textContent,links:[...e.querySelectorAll('a')].map(a=>({text:a.textContent,href:a.href})),buttons:[...e.querySelectorAll('button')].map(b=>({text:b.textContent,label:b.getAttribute('aria-label')}))})),matches:[...document.querySelectorAll('a')].filter(a=>a.textContent.includes('دریا')&&a.textContent.includes('فلورا')).map(a=>({text:a.textContent,href:a.href})),uploading:document.querySelector('#upload-button')?.textContent}));
 writeFileSync(path.join(dir,'observed-result.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
}finally{await b.close();}
